// Bundle backend.ts into ../matlab/webgpu/_fmm3dbie_gpu_backend.numbl.js: a
// numbl library file that returns the source of a factory function for
// gpu.load(). The bundle is committed; rerun after changing backend/*.ts.
//   NUMBL=/path/to/numbl node backend/build.mjs   (esbuild from a numbl
//   checkout, default ~/projects/numbl)
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(process.env.NUMBL || join(homedir(), 'projects/numbl'), 'package.json'));
const esbuild = require('esbuild');

const r = await esbuild.build({
  entryPoints: [join(here, 'backend.ts')],
  bundle: true,
  format: 'iife',
  globalName: '__fmm3dbie_gpu',
  target: 'es2022',
  write: false,
});
const iife = r.outputFiles[0].text;
const factory = `function () {\n${iife}\nreturn __fmm3dbie_gpu.backend;\n}`;
const out = `// Generated by backend/build.mjs from backend/*.ts; do not edit.\nreturn ${JSON.stringify(factory)};\n`;
const dest = join(here, '..', 'matlab', 'webgpu', '_fmm3dbie_gpu_backend.numbl.js');
writeFileSync(dest, out);
console.log(`wrote ${dest} (${(out.length / 1024).toFixed(0)} KB)`);
